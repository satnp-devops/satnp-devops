/** Icons for org unit types; new types fall back to a neutral mark. */
export function unitIcon(type: string): IconName {
  switch (type) {
    case 'group':
      return 'layers';
    case 'company':
      return 'building';
    case 'region':
      return 'map';
    case 'branch':
      return 'pin';
    case 'team':
      return 'users';
    default:
      return 'dot';
  }
}
